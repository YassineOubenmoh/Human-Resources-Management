    private void UpdatePositionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdatePositionActionPerformed
        // TODO add your handling code here:
        try {
            String positionCombo = (String) PositionComboAction.getSelectedItem();
            String departementCombo = (String) DepartementComboAction.getSelectedItem();

            // Parameterized queries to prevent SQL injection
            int row = TablePositionDetails.getSelectedRow();
            String value = (TablePositionDetails.getModel().getValueAt(row, 0).toString());

            String QueryModification = "UPDATE employee_details INNER JOIN positions ON employee_details.positionId = positions.id_position INNER JOIN departement ON employee_details.depId = departement.depId SET employee_details.firstName = ?, employee_details.lastName = ?, positions.positionName = ?, departement.departementName = ? WHERE empId = ?";

            // Prepare statements
            ps = conn.prepareStatement(QueryModification);

            ps.setString(1, FirstNamePosition.getText());
            ps.setString(2, LastNamePosition.getText());
            ps.setString(3, positionCombo);
            ps.setString(4, departementCombo);
            ps.setString(5, value);

         

            ps.executeUpdate();

            JOptionPane.showMessageDialog(null, "Your modification has been done successfully");

        } catch (Exception e) {
            System.out.println("--> Exception : " + e);
            JOptionPane.showMessageDialog(null, "An unexpected error occurred. Please contact support.");
        }

    }//GEN-LAST:event_UpdatePositionActionPerformed

    
