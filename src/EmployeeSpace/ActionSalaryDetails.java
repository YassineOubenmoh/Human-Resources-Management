    private void DeleteSalaryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteSalaryActionPerformed
        // TODO add your handling code here:
        try {
    // Parameterized query to prevent SQL injection
    int row = TableSalaryAction.getSelectedRow();
    String empId = (TableSalaryAction.getModel().getValueAt(row, 0).toString());
    
    String QueryDeletion = "DELETE FROM employee_details WHERE empId = ?";
    
    // Prepare statement
    ps = conn.prepareStatement(QueryDeletion);
    
    ps.setString(1, empId);
    
    int rowsAffected = ps.executeUpdate();
    
    if (rowsAffected > 0) {
        JOptionPane.showMessageDialog(null, "Employee record with ID " + empId + " has been deleted successfully");
    } else {
        JOptionPane.showMessageDialog(null, "No employee record found with ID " + empId);
    }

} catch (Exception e) {
    System.out.println("--> Exception : " + e);
    JOptionPane.showMessageDialog(null, "An unexpected error occurred. Please contact support.");
}

    }//GEN-LAST:event_DeleteSalaryActionPerformed

