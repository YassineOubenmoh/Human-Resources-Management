            String id = TablePositionDetails.getValueAt(selectedRow, 0).toString();
            String firstName = TablePositionDetails.getValueAt(selectedRow, 1).toString();
            String lastName = TablePositionDetails.getValueAt(selectedRow, 2).toString();
            String positionName = TablePositionDetails.getValueAt(selectedRow, 3).toString();
            String departementName = TablePositionDetails.getValueAt(selectedRow, 4).toString();

            // Set the retrieved data into the fields in your JFrame
