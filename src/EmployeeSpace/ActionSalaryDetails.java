    private void UpdateSalaryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateSalaryActionPerformed
        // TODO add your handling code here:
try {
    String SalaryRange = (String) SalaryRangeCombo.getSelectedItem();


    // Parameterized queries to prevent SQL injection
    int row = TableSalaryAction.getSelectedRow();
    String value = (TableSalaryAction.getModel().getValueAt(row, 0).toString());
    
    String QueryModification = "UPDATE employee_details INNER JOIN employee_salary ON employee_details.empId = employee_salary.empId SET employee_details.firstName = ?, employee_details.lastName = ?, employee_salary.salaryRange = ?, employee_salary.annualIncome = ?, employee_salary.loans = ?, employee_salary.insurance = ? WHERE employee_salary.empId = ?";
    
    // Prepare statements
    ps = conn.prepareStatement(QueryModification);

    

    ps.setString(1, FirstNameSalaryAction.getText());
    ps.setString(2, LastNameSalaryAction.getText());
    ps.setString(3, SalaryRange);
    ps.setString(4, AnnualIncomeField.getText());
    ps.setString(5, LoansField.getText());
    ps.setString(6, InsuranceField.getText());
    ps.setString(7, value);
   
    ps.executeUpdate();
    
    JOptionPane.showMessageDialog(null, "Your modification has been done successfully");

} catch (Exception e) {
    System.out.println("--> Exception : " + e);
    JOptionPane.showMessageDialog(null, "An unexpected error occurred. Please contact support.");
}


      
 
  
    }//GEN-LAST:event_UpdateSalaryActionPerformed

