    private void ShowSalariesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ShowSalariesActionPerformed
        // TODO add your handling code here:
       try {
    // Load the MySQL JDBC driver
    Class.forName("com.mysql.cj.jdbc.Driver");

    // Establish a connection to the database
    try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/humanresourcesfinal?useSSL=false", "root", "")) {
        Statement st = con.createStatement();

        // SQL query to fetch employee details
        String sql = "SELECT employee_details.empId, employee_details.firstName, employee_details.lastName, employee_salary.salaryRange, employee_salary.annualIncome, employee_salary.loans, employee_salary.insurance FROM employee_salary INNER JOIN employee_details ON employee_salary.empId = employee_details.empId";
        ResultSet rs = st.executeQuery(sql);

        // Create a DefaultTableModel with column names
        DefaultTableModel tblModel = new DefaultTableModel();
        tblModel.setColumnIdentifiers(new String[]{"EmpId", "First Name", "Last Name", "Salary Range", "Annual Income", "Loans", "Insurance"});

        // Loop through the result set and add rows to the table model
        while (rs.next()) {
            String empId = String.valueOf(rs.getInt("empId"));
            String firstName = rs.getString("firstName");
            String lastName = rs.getString("lastName");
            String salaryRange = rs.getString("salaryRange");
            String annualIncome = String.valueOf(rs.getInt("annualIncome"));
            String loans = String.valueOf(rs.getInt("loans"));
            String insurance = String.valueOf(rs.getInt("insurance"));

            String[] tbData = {empId, firstName, lastName, salaryRange, annualIncome, loans, insurance};
            tblModel.addRow(tbData);
        }

        // Set the table model to your jTable1
        TableSalaryAction.setModel(tblModel);

        // Increase the font size of the table
        TableSalaryAction.setFont(new Font("Segoe UI", Font.PLAIN, 18));

        // Increase the font size of the header
        JTableHeader header = TableSalaryAction.getTableHeader();
        header.setFont(new Font("Segoe UI", Font.BOLD, 14));
    } catch (SQLException ex) {
        // Handle SQL exceptions
        Logger.getLogger(Employees.class.getName()).log(Level.SEVERE, null, ex);
        // You can add code here to display an error message to the user if desired
    }
} catch (ClassNotFoundException ex) {
    // Handle class not found exceptions (e.g., missing JDBC driver)
    Logger.getLogger(Employees.class.getName()).log(Level.SEVERE, null, ex);
    // You can add code here to display an error message to the user if desired
}

    }//GEN-LAST:event_ShowSalariesActionPerformed

    
